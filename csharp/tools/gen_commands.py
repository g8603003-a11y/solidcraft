#!/usr/bin/env python3
"""Generate csharp/SolidCraft.Net/Commands.g.cs from the engine's command registry.

Reads every `CommandSpec::new("id", "label", …)` in crates/engine/src/cmd/**/*.rs with its
`.at(tab, panel)`, `.key(..)` and `.params(..)` docs, and writes one C# constant per command,
grouped by the id's first segment, with the params doc as the IntelliSense summary.

    python3 csharp/tools/gen_commands.py            # from the repo root
    python3 csharp/tools/gen_commands.py --check    # fail when the file is out of date
"""
import glob
import html
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CMD_DIR = os.path.join(ROOT, "crates", "engine", "src", "cmd")
OUT = os.path.join(ROOT, "csharp", "SolidCraft.Net", "Commands.g.cs")
STR = r'"((?:[^"\\]|\\.)*)"'

MACROS = {
    "model_operand_doc": "; any of them may be a model edge {edge: [x,y,z], body?} or vertex {vertex: [x,y,z], body?}, projected into the sketch first (reported in created)",
    "refs_doc": "refs: [{edge: [x,y,z], body?} | {face: [x,y,z], body?} (its edge loops) | {body: name} (silhouette) | {vertex: [x,y,z], body?} | {sketch, curve} | {sketch, point} | \"origin\" | {axis: X|Y|Z} | {plane: XY|XZ|YZ|name}]",
    "connect_doc": "; connect?: bool (default true: a new point landing exactly on an existing point, the origin too, is made coincident with it)",
    "created_doc": ". Returns created: {points, curves, constraints, dimensions}: the ids of what it added (stable and never reused: usable right away in sketch.dimension, sketch.constraint.*, sketch.delete…)",
}


def unesc(s):
    s = re.sub(r"\\\n\s*", "", s)
    return s.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def skip_string(src, j):
    """j at an opening quote; return the index after the closing quote."""
    j += 1
    while src[j] != '"':
        if src[j] == "\\":
            j += 1
        j += 1
    return j + 1


def call_args(span, name):
    """The text inside `.name( … )`, or None."""
    m = re.search(r"\." + name + r"\(", span)
    if not m:
        return None
    k = m.end()
    depth, q = 1, k
    while q < len(span) and depth:
        c = span[q]
        if c == '"':
            q = skip_string(span, q)
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        q += 1
    return span[k:q - 1]


def doc_text(inner):
    parts = [unesc(x) for x in re.findall(STR, inner, re.S)]
    rest = re.sub(STR, "", inner, flags=re.S)
    for mac in re.findall(r"(\w+)!\(\)", rest):
        parts.append(MACROS.get(mac, ""))
    return "".join(parts)


def extract():
    out = []
    for f in sorted(glob.glob(os.path.join(CMD_DIR, "**", "*.rs"), recursive=True)):
        src = open(f, encoding="utf-8").read()
        for m in re.finditer(r"CommandSpec::new\(\s*" + STR + r"\s*,\s*" + STR, src, re.S):
            i = m.start()
            depth, j = 0, i
            while j < len(src):
                c = src[j]
                if c == '"':
                    j = skip_string(src, j)
                    continue
                if c == "(":
                    depth += 1
                elif c == ")":
                    depth -= 1
                elif c in ",;" and depth == 0:
                    break
                j += 1
            span = src[i:j]
            at = re.search(r"\.at\(\s*" + STR + r"\s*,\s*" + STR, span, re.S)
            key = call_args(span, "key")
            params = call_args(span, "params")
            out.append({
                "id": unesc(m.group(1)),
                "label": unesc(m.group(2)),
                "tab": at.group(1) if at else "",
                "panel": at.group(2) if at else "",
                "key": doc_text(key) if key else "",
                "params": doc_text(params) if params else "",
            })
    ids = [o["id"] for o in out]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate command ids: {dupes}")
    return sorted(out, key=lambda o: o["id"])


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[._\-\s]+", s) if p)


def xml(s):
    return html.escape(s, quote=False)


def generate(cmds):
    groups = {}
    for c in cmds:
        head, _, rest = c["id"].partition(".")
        groups.setdefault(head, []).append((rest or head, c))
    lines = [
        "// <auto-generated>",
        "// Generated by csharp/tools/gen_commands.py from crates/engine/src/cmd/**/*.rs. Do not edit.",
        "// </auto-generated>",
        "",
        "namespace SolidCraft;",
        "",
        "/// <summary>Every engine command id, with its parameters as the app documents them.</summary>",
        "public static class Commands",
        "{",
    ]
    for head in sorted(groups):
        cls = pascal(head)
        lines.append(f"    /// <summary><c>{head}.*</c> commands.</summary>")
        lines.append(f"    public static class {cls}")
        lines.append("    {")
        used = set()
        for rest, c in groups[head]:
            name = pascal(rest)
            if name == cls or name in used or not name[0].isalpha():
                name = name + "_"
            used.add(name)
            where = f"{c['tab']} › {c['panel']}" if c["tab"] else "not on the toolbar"
            shortcut = f", shortcut {c['key']}" if c["key"] else ""
            lines.append(f"        /// <summary>{xml(c['label'])} ({where}{shortcut}).</summary>")
            if c["params"]:
                doc = xml(c["params"]).replace("\n", " ")
                lines.append(f"        /// <remarks>{doc}</remarks>")
            lines.append(f'        public const string {name} = "{c["id"]}";')
        lines.append("    }")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("")
    lines.append("    /// <summary>Every command id, sorted.</summary>")
    lines.append("    public static readonly string[] All =")
    lines.append("    {")
    for c in cmds:
        lines.append(f'        "{c["id"]}",')
    lines.append("    };")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    cmds = extract()
    text = generate(cmds)
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit(f"{OUT} is out of date: run csharp/tools/gen_commands.py")
        print(f"{OUT} is up to date ({len(cmds)} commands)")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    if "--json" in sys.argv:
        with open(os.path.join(ROOT, "csharp", "tools", "commands.json"), "w", encoding="utf-8") as f:
            json.dump(cmds, f, ensure_ascii=False, indent=1)
    print(f"wrote {OUT}: {len(cmds)} commands, {sum(1 for c in cmds if c['params'])} with params docs")


if __name__ == "__main__":
    main()
